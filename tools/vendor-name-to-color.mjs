import {writeFile} from 'node:fs/promises';

const REF = '24433eef070b99891a1d0546c2c755d69e5e2f2b';
const BASE = `https://raw.githubusercontent.com/zonaro/NameToColor/${REF}`;
const sources = ['NameToColor.js', 'NameToColor.ptBR.js'];

const parts = [];
for (const source of sources) {
    const response = await fetch(`${BASE}/${source}`);
    if (!response.ok)
        throw new Error(`Could not fetch ${source}: HTTP ${response.status}`);
    parts.push(await response.text());
}

const banner = `// Vendored from https://github.com/zonaro/NameToColor
// Source ref: ${REF}
// Files: NameToColor.js + NameToColor.ptBR.js
// Generated by tools/vendor-name-to-color.mjs; do not edit by hand.
`;

const adapter = `
function normalizeStickyColor(value) {
    if (typeof value !== 'string')
        return null;
    let hex = value.trim().toLowerCase();
    if (/^#[0-9a-f]{3}$/.test(hex)) {
        const [r, g, b] = hex.slice(1);
        hex = \`#\${r}\${r}\${g}\${g}\${b}\${b}\`;
    }
    return /^#[0-9a-f]{6}$/.test(hex) ? hex : null;
}

/**
 * Resolve a user expression through NameToColor while exposing only opaque
 * six-digit colors that are safe to interpolate into GNOME Shell CSS.
 */
export function resolveNameToColor(value) {
    if (typeof value !== 'string' || !value.trim())
        return null;
    return normalizeStickyColor(generateColor(value.trim()));
}

export const NAME_TO_COLOR_SOURCE_REF = '${REF}';
`;

const output = new URL('../extension/name-to-color.js', import.meta.url);
await writeFile(output, `${banner}\n${parts.join('\n\n')}\n${adapter}`, 'utf8');
console.log(`Wrote ${output.pathname}`);
