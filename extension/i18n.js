export function t(message) {
    const locales = GLib.get_language_names().map(locale => locale.toLowerCase());
    const primary = locales[0] ?? 'en';
    if (primary.startsWith('pt'))
        return PT[message] ?? message;
    if (primary.startsWith('es'))
        return ES[message] ?? message;
    return message;
}
